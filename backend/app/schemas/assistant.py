from typing import List, Optional, Literal
from pydantic import BaseModel, Field


class ChatMessage(BaseModel):
    role: Literal["user", "assistant", "system"]
    content: str
    timestamp: Optional[str] = None


class AssistantChatRequest(BaseModel):
    message: str = Field(..., min_length=1, max_length=4000, description="User's query")
    session_id: Optional[str] = Field(None, description="Optional conversational session ID")
    history: Optional[List[ChatMessage]] = Field(default_factory=list, description="Recent conversation turns")
    context_module: Optional[str] = Field(None, description="Optional active module context (e.g. safety, crack, planning)")


class AssistantChatResponse(BaseModel):
    response_text: str
    technical_concepts: List[str] = Field(default_factory=list, description="Key technical terms referenced and explained")
    suggested_followups: List[str] = Field(default_factory=list, description="Useful related topics the user can explore")
    professional_advisory_notice: str = Field(
        default="This guidance is generated by AI for educational and preliminary decision-support. Construction procedures, structural modifications, and safety-critical work must be signed off by licensed civil/structural engineers and safety officers.",
        description="Engineering advisory notice"
    )
    is_demo: bool = False
    session_id: str
